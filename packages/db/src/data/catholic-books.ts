export function getBookByCode(code: string): CanonicalBook | undefined {
  const normalized = code.toLowerCase().trim();
  return CATHOLIC_BOOKS.find((b) => b.code.toLowerCase() === normalized);
}

export function getBookById(id: number): CanonicalBook | undefined {
  return CATHOLIC_BOOKS.find((b) => b.id === id);
}
